ADVANCE, HEIGHT = 6, 7


def to_ascii(text):
    """é -> e, œ -> oe, other non-ASCII characters dropped."""
    text = text.replace("œ", "oe").replace("Œ", "OE").replace("æ", "ae").replace("ß", "ss")
    text = unicodedata.normalize("NFKD", text)
    return "".join(ch for ch in text if ch in GLYPHS)


def width(text):
    return len(to_ascii(text)) * ADVANCE


def draw(img, x, y, text, colour):
    """Draw `text` into img (numpy H x W x 3) with its top-left at (x, y); returns the new x."""
    H, W = img.shape[:2]
    for ch in to_ascii(text):
        for cx, col in enumerate(GLYPHS[ch]):
            for row in range(HEIGHT):
                if col >> row & 1 and 0 <= x + cx < W and 0 <= y + row < H:
                    img[y + row, x + cx] = colour
        x += ADVANCE
    return x
